"""Compile the generated element icon cutouts into the embedded 32x32 HUD atlas.

Same conversion as tools/pack_upgrade_sprites.py: alpha-bound trim, aspect-
preserving fit, 32-colour palette, PS1 5-bit RGB, retained edge alpha.
Outputs assets/ui/elements/{<name>.png,element-atlas.png,sprite-review.png,
manifest.json} and src/generated/element_icon_pixels.inc.

Row 2 (y 32-47) holds the power-meter emblems that replace the retail
superwing: GPT Image sheets on flat magenta (meter-emblems-v2-source.png for
fire/water/electricity, meter-emblems-source.png for ice/convexity), keyed to
1-bit transparency, fitted into 30x16, 16 colours and PS1 5-bit RGB.
"""
from pathlib import Path
import hashlib, json
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parents[1]
folder = root / 'assets/ui/elements'
names = ['fire', 'water', 'ice', 'electricity', 'convexity']
atlas = Image.new('RGBA', (32 * len(names), 48))
review = Image.new('RGBA', (len(names) * 120, 170), (35, 24, 54, 255))
draw = ImageDraw.Draw(review)
manifest = []
for i, name in enumerate(names):
    path = folder / 'source' / f'{name}.png'
    source = Image.open(path).convert('RGBA')
    alpha = source.getchannel('A')
    assert alpha.getextrema()[0] == 0, f'{name}: expected real transparent alpha'
    bounds = alpha.point(lambda a: 255 if a > 8 else 0).getbbox()
    im = source.crop(bounds)
    im.thumbnail((30, 30), Image.Resampling.BOX)
    a = im.getchannel('A')
    im = im.convert('RGB').quantize(colors=32, method=Image.Quantize.MEDIANCUT).convert('RGB')
    im = im.point([((v >> 3) << 3) | ((v >> 3) >> 2) for v in range(256)] * 3).convert('RGBA')
    im.putalpha(a)
    tile = Image.new('RGBA', (32, 32)); tile.alpha_composite(im, ((32 - im.width) // 2, (32 - im.height) // 2))
    tile.save(folder / f'{name}.png')
    atlas.alpha_composite(tile, (i * 32, 0))
    review.alpha_composite(tile.resize((96, 96), Image.Resampling.NEAREST), (i * 120 + 12, 12))
    review.alpha_composite(tile, (i * 120 + 44, 116))
    draw.text((i * 120 + 14, 152), name, fill=(241, 211, 145))
    manifest.append({'name': name, 'source_sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'source_size': source.size,
                     'source_bounds': bounds, 'atlas_rect': [i * 32, 0, 32, 32]})
# Power-meter emblems (row 2): cell k of an evenly spaced magenta sheet.
emblem_sources = {'fire': ('meter-emblems-v2-source.png', 0, 3), 'water': ('meter-emblems-v2-source.png', 1, 3),
                  'ice': ('meter-emblems-source.png', 2, 5), 'electricity': ('meter-emblems-v2-source.png', 2, 3),
                  'convexity': ('meter-emblems-source.png', 4, 5)}
emblems = []
for i, name in enumerate(names):
    sheet_name, cell, cells = emblem_sources[name]
    sheet = Image.open(folder / sheet_name).convert('RGB')
    w = sheet.width / cells
    crop = sheet.crop((round(cell * w), 0, round((cell + 1) * w), sheet.height))
    px = crop.load(); key = Image.new('L', crop.size, 0); kp = key.load()
    for y in range(crop.height):
        for x in range(crop.width):
            r, g, b = px[x, y]
            kp[x, y] = 0 if (r > 170 and b > 170 and g < 90) else 255   # magenta background
    bounds = key.getbbox()
    rgba = crop.convert('RGBA'); rgba.putalpha(key); rgba = rgba.crop(bounds)
    scale = min(30 / rgba.width, 16 / rgba.height)
    size = (max(1, round(rgba.width * scale)), max(1, round(rgba.height * scale)))
    small = rgba.resize(size, Image.Resampling.BOX)
    a = small.getchannel('A').point(lambda v: 255 if v >= 128 else 0)
    rgb = small.convert('RGB').quantize(colors=16, method=Image.Quantize.MEDIANCUT).convert('RGB')
    rgb = rgb.point([((v >> 3) << 3) | ((v >> 3) >> 2) for v in range(256)] * 3).convert('RGBA'); rgb.putalpha(a)
    x0, y0 = i * 32 + (32 - size[0]) // 2, 32 + (16 - size[1]) // 2
    atlas.alpha_composite(rgb, (x0, y0))
    rgb.save(folder / f'meter-{name}.png')
    emblems.append({'name': name, 'source': sheet_name, 'cell': cell, 'atlas_rect': [x0, y0, size[0], size[1]],
                    'source_sha256': hashlib.sha256((folder / sheet_name).read_bytes()).hexdigest()})
    review.alpha_composite(rgb.resize((size[0] * 3, size[1] * 3), Image.Resampling.NEAREST), (i * 120 + 14, 128 - size[1] * 3))
atlas.save(folder / 'element-atlas.png')
review.save(folder / 'sprite-review.png')
(folder / 'manifest.json').write_text(json.dumps({'tile_size': 32, 'rgb_depth': 5, 'colours_per_sprite': 32, 'sprites': manifest, 'meter_emblems': emblems}, indent=2) + '\n')
values = [r | (g << 8) | (b << 16) | (a << 24) for r, g, b, a in atlas.getdata()]
out = root / 'src/generated/element_icon_pixels.inc'
out.write_text('// Generated by tools/pack_element_icons.py from GPT Image sources.\n' +
               'constexpr std::uint32_t element_icon_pixels[]{\n' +
               '\n'.join('    ' + ','.join(f'0x{v:08x}' for v in values[i:i + 10]) + ',' for i in range(0, len(values), 10)) + '\n};\n')
print(json.dumps({'atlas': str(folder / 'element-atlas.png'), 'sprites': len(names), 'embedded_bytes': len(values) * 4}))
