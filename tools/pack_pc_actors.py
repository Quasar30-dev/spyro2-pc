"""Pack the Blender-authored demons into .s2actor files and embed them.

    python tools/pack_pc_actors.py

Inputs: assets/actors/build/<id>.json (tools/build_demon_actors.py) and the
generated texture swatch sheets assets/actors/source/<id>-sheet.png. Each 2x2
sheet becomes a 128x128 texture (four 64x64 swatches), quantised to a 16-colour
PS1 CLUT (5-bit BGR, word 0 reserved for transparency) and 4bpp indices.
Outputs: assets/actors/<id>.s2actor, assets/actors/manifest.json,
assets/actors/texture-review.png and src/generated/pc_actor_data.inc.
"""
import hashlib, json, struct, sys, zlib
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ACTORS = ROOT / 'assets' / 'actors'
ORDER = ['imp', 'hound', 'wraith', 'maw']


def texture(sheet_path):
    sheet = Image.open(sheet_path).convert('RGB')
    w, h = sheet.size
    side = min(w, h)
    sheet = sheet.crop(((w - side) // 2, (h - side) // 2, (w - side) // 2 + side, (h - side) // 2 + side))
    out = Image.new('RGB', (128, 128))
    half = side // 2
    for qy in range(2):
        for qx in range(2):
            # Trim a small inset so grid seams in the generated sheet never sample.
            inset = max(2, half // 32)
            cell = sheet.crop((qx * half + inset, qy * half + inset, (qx + 1) * half - inset, (qy + 1) * half - inset))
            out.paste(cell.resize((64, 64), Image.LANCZOS), (qx * 64, qy * 64))
    quant = out.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG)
    pal = quant.getpalette()[:48]
    while len(pal) < 48: pal += [0, 0, 0]
    words = []
    for i in range(16):
        r, g, b = pal[i * 3:i * 3 + 3]
        word = (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
        if word == 0: word = 1 << 10   # never collide with the transparent word
        words.append(word)
    indices = list(quant.getdata())
    return words, indices, quant.convert('RGB')


def encode(data, words, indices):
    clips = data['clips']
    attachments = len(clips[0]['attachments'][0])
    body = bytearray(b'S2ACTOR1')
    body += struct.pack('<10I', data['kind'], data['vertices'], len(data['faces']), len(clips), 128, 128, 16, attachments, len(data['spheres']), 0)
    body += struct.pack('<16H', *words)
    for i in range(0, 128 * 128, 2):
        body.append((indices[i] & 15) | ((indices[i + 1] & 15) << 4))
    for f in data['faces']:
        v = list(f['v']) + [f['v'][-1]] * (4 - len(f['v']))
        uv = list(f['uv']) + [f['uv'][-1]] * (4 - len(f['uv']))
        rgb = list(f['rgb']) + [f['rgb'][-1]] * (4 - len(f['rgb']))
        body += bytes(v) + bytes([1 if f['quad'] else 0, 0, 0, 0])
        for u, t in uv: body += bytes([u, t])
        for c in rgb: body += bytes(c)
    for clip in clips:
        body += struct.pack('<2I', len(clip['frames']), clip['ticks'])
        for frame in clip['frames']:
            assert len(frame) == data['vertices']
            for p in frame: body += struct.pack('<3h', *p)
        for att in clip['attachments']:
            for p in att: body += struct.pack('<3h', *p)
    for vertex, radius in data['spheres']: body += struct.pack('<2H', vertex, radius)
    body += struct.pack('<I', zlib.crc32(bytes(body)) & 0xffffffff)
    return bytes(body)


def main():
    manifest, blobs = [], []
    review = Image.new('RGB', (128 * len(ORDER), 128))
    for k, name in enumerate(ORDER):
        data = json.loads((ACTORS / 'build' / f'{name}.json').read_text())
        sheet = ACTORS / 'source' / f'{name}-sheet.png'
        if not sheet.exists():
            sys.exit(f'missing generated texture sheet: {sheet}')
        words, indices, preview = texture(sheet)
        review.paste(preview, (k * 128, 0))
        blob = encode(data, words, indices)
        (ACTORS / f'{name}.s2actor').write_bytes(blob)
        blobs.append(blob)
        manifest.append({'id': name, 'kind': data['kind'], 'vertices': data['vertices'], 'faces': len(data['faces']),
                         'clips': [c['name'] for c in data['clips']], 'frames_per_clip': len(data['clips'][0]['frames']),
                         'ticks_per_frame': data['clips'][0]['ticks'], 'bytes': len(blob),
                         'sheet_sha256': hashlib.sha256(sheet.read_bytes()).hexdigest(),
                         's2actor_sha256': hashlib.sha256(blob).hexdigest()})
    review.resize((review.width * 3, review.height * 3), Image.NEAREST).save(ACTORS / 'texture-review.png')
    (ACTORS / 'manifest.json').write_text(json.dumps({'format': 'S2ACTOR1', 'texture': '128x128 4bpp 16-colour CLUT', 'actors': manifest}, indent=2))
    data = b''.join(blobs)
    offsets, at = [], 0
    for b in blobs: offsets.append(at); at += len(b)
    lines = ['// Generated by tools/pack_pc_actors.py from assets/actors (Blender + generated swatch sheets).',
             f'constexpr unsigned pc_actor_count={len(blobs)};',
             f'const unsigned char pc_actor_blob[{len(data)}]={{']
    for i in range(0, len(data), 32):
        lines.append(','.join(str(x) for x in data[i:i + 32]) + ',')
    lines.append('};')
    lines.append(f'const unsigned pc_actor_offset[{len(blobs)}]={{{",".join(map(str, offsets))}}};')
    lines.append(f'const unsigned pc_actor_size[{len(blobs)}]={{{",".join(str(len(b)) for b in blobs)}}};')
    (ROOT / 'src' / 'generated' / 'pc_actor_data.inc').write_text('\n'.join(lines) + '\n')
    print('packed', len(blobs), 'actors,', len(data), 'bytes')


if __name__ == '__main__':
    main()
