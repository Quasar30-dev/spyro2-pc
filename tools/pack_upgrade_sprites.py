"""Compile GPT Image source cutouts to the small, embedded PC HUD atlas.

This is an asset conversion step: alpha-preserving resize, palette conversion,
packing and C++ data emission. Original generated artwork stays untouched.
"""
from pathlib import Path
import hashlib, json
from PIL import Image, ImageDraw

root=Path(__file__).resolve().parents[1]
folder=root/'assets/ui/upgrades'
names=['supercharge','superflame','superfly','glide','carry','melee']
atlas=Image.new('RGBA',(384,64))
review=Image.new('RGBA',(960,220),(35,24,54,255))
draw=ImageDraw.Draw(review)
manifest=[]
for i,name in enumerate(names):
    path=folder/'source'/f'{name}.png'
    source=Image.open(path).convert('RGBA')
    alpha=source.getchannel('A')
    assert alpha.getextrema()==(0,255),f'{name}: expected real transparent alpha'
    bounds=alpha.getbbox()
    im=source.crop(bounds)
    im.thumbnail((56,56),Image.Resampling.BOX)
    a=im.getchannel('A')
    # Match the retail colour depth while retaining the generated edge alpha.
    im=im.convert('RGB').quantize(colors=32,method=Image.Quantize.MEDIANCUT).convert('RGB')
    im=im.point([((v>>3)<<3)|((v>>3)>>2) for v in range(256)]*3).convert('RGBA')
    im.putalpha(a)
    tile=Image.new('RGBA',(64,64));tile.alpha_composite(im,((64-im.width)//2,(64-im.height)//2))
    tile.save(folder/f'{name}.png')
    atlas.alpha_composite(tile,(i*64,0))
    review.alpha_composite(tile.resize((128,128),Image.Resampling.NEAREST),(i*160+16,18))
    review.alpha_composite(tile,(i*160+48,142))
    draw.text((i*160+22,207),name,fill=(241,211,145))
    manifest.append({'name':name,'source_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'source_size':source.size,'source_bounds':bounds,'atlas_rect':[i*64,0,64,64],'alpha_min':0,'alpha_max':255})
atlas.save(folder/'upgrade-atlas.png')
review.save(folder/'sprite-review.png')
(folder/'manifest.json').write_text(json.dumps({'tile_size':64,'rgb_depth':5,'colours_per_sprite':32,'sprites':manifest},indent=2)+'\n')
values=[r|(g<<8)|(b<<16)|(a<<24) for r,g,b,a in atlas.getdata()]
out=root/'src/generated/upgrade_pixels.inc';out.parent.mkdir(exist_ok=True)
out.write_text('// Generated by tools/pack_upgrade_sprites.py from GPT Image sources.\n'+
    'constexpr std::uint32_t upgrade_pixels[]{\n'+
    '\n'.join('    '+','.join(f'0x{v:08x}' for v in values[i:i+12])+',' for i in range(0,len(values),12))+'\n};\n')
print(json.dumps({'atlas':str(folder/'upgrade-atlas.png'),'sprites':len(names),'embedded_bytes':len(values)*4}))
